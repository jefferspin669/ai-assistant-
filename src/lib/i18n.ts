const shells: Record<AppLanguage, Dict> = {
  en: shellEn,
  es: shellEs,
  fr: shellFr,
  de: shellDe,
  pt: shellPt,
};

const navMaps: Record<AppLanguage, Dict> = {
  en: {},
  es: navEs,
  fr: navFr,
  de: navDe,
  pt: navPt,
};

export function normalizeLanguage(value: string | null | undefined): AppLanguage {
  const id = (value || "en").toLowerCase().slice(0, 2) as AppLanguage;
  return shells[id] ? id : "en";
}

export function loadUiLanguage(): AppLanguage {
  if (typeof window === "undefined") return "en";
  try {
    return normalizeLanguage(localStorage.getItem(STORAGE_KEY));
  } catch {
    return "en";
  }
}

export function saveUiLanguage(lang: AppLanguage) {
  if (typeof window === "undefined") return;
  localStorage.setItem(STORAGE_KEY, lang);
  document.documentElement.lang = lang;
}

export function translate(lang: AppLanguage, key: string, fallback?: string): string {
  return shells[lang]?.[key] ?? shellEn[key] ?? fallback ?? key;
}

export function translateNavLabel(lang: AppLanguage, label: string): string {
  if (lang === "en") return label;
  return navMaps[lang]?.[label] ?? label;
}

export function translateTitle(lang: AppLanguage, title: string): string {
  return translate(lang, `title.${title}`, title);
}

export function translateAction(lang: AppLanguage, label: string): string {
  return translate(lang, `action.${label}`, label);
}
